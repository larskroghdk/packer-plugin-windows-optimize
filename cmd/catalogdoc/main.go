// Command catalogdoc generates docs/catalog.md from the embedded optimization
// catalog: a summary, an OS compatibility matrix computed with the same
// applicability rules the plugin uses, and one section per optimization with
// its changes, impact and sources.
//
// Usage:
//
//	go run ./cmd/catalogdoc [-check] [-o docs/catalog.md]
//
// With -check it writes nothing and exits with status 1 when the file is out of
// date. CRLF line endings from a Windows checkout are ignored.
package main

